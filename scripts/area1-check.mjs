import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';

await fs.mkdir('qa', { recursive: true });
const seedBackup = await fs.readFile('data/area1.json', 'utf8');
const browser = await chromium.launch({ headless: true });
const errors = [];
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
const page = await context.newPage();
page.on('pageerror', (error) => errors.push(`pageerror: ${error.message}`));
page.on('console', (message) => { if (message.type() === 'error') errors.push(`console: ${message.text()}`); });
const base = 'http://127.0.0.1:5173';
const noOverflow = async (target = page, label = 'page') => {
  const dimensions = await target.evaluate(() => ({ scroll: document.documentElement.scrollWidth, viewport: window.innerWidth }));
  assert.ok(dimensions.scroll <= dimensions.viewport + 1, `${label}: horizontal overflow ${dimensions.scroll} > ${dimensions.viewport}`);
};
const dismissToasts = async () => {
  const buttons = page.locator('.toast button');
  while (await buttons.count()) await buttons.first().click();
};
const clickExport = async (format) => {
  await page.getByRole('button', { name: 'Esporta', exact: true }).click();
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('menuitem').filter({ hasText: `.${format.toUpperCase()}` }).click();
  return downloadPromise;
};

try {
  await page.goto(base, { waitUntil: 'networkidle' });
  const standardLinks = page.locator('#area-compliance .service-item__action');
  await expect(standardLinks).toHaveCount(4);
  await expect(page.locator('#area-compliance .service-item').nth(4).locator('.service-item__action')).toHaveCount(0);
  await page.locator('#servizi .mode-switch button').nth(1).click();
  await expect(page.locator('#area-compliance .variant-item__action')).toHaveCount(3);
  await page.locator('#servizi .mode-switch button').nth(0).click();
  await standardLinks.first().click();
  await expect(page).toHaveURL(/\/app\/esg\/scope-3$/);
  await expect(page.locator('.dataset-list > button')).toHaveCount(2);
  await expect(page.getByRole('heading', { name: 'Il dato ambientale. Con tutto il suo contesto.' })).toBeVisible();
  await page.getByRole('button', { name: 'Confronta versioni' }).click();
  await expect(page.locator('.version-comparison')).toBeVisible();
  await expect(page.locator('.comparison-delta strong')).toContainText('-0,35');
  const csv = await clickExport('csv');
  assert.match(csv.suggestedFilename(), /scope-3-.*\.csv$/);
  const csvText = await fs.readFile(await csv.path(), 'utf8');
  assert.match(csvText, /demo/);
  assert.match(csvText, /18,6|18.6/);
  await expect(page.locator('.download-history li')).toHaveCount(1);
  await noOverflow(page, 'C01 desktop');
  await dismissToasts();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: 'qa/area1-c01-desktop.png' });

  await page.locator('.workspace-nav a[href="/app/fondo/attestazioni"]').click();
  await expect(page.locator('.attestation-document')).toBeVisible();
  await expect(page.locator('.reconciliation-banner')).toContainText('coerenti');
  await expect(page.locator('.formula-flow')).toContainText('4500,00');
  const publicFundUrl = await page.locator('.public-verification-box code').innerText();
  const publicFund = await context.newPage();
  await publicFund.goto(publicFundUrl, { waitUntil: 'networkidle' });
  await expect(publicFund.locator('.public-fund-card')).toBeVisible();
  const publicFundText = await publicFund.locator('main').innerText();
  assert.ok(!publicFundText.includes('15.000') && !publicFundText.includes('4.500') && !publicFundText.includes('General Contractor'), 'Public fund verification leaks commercial data');
  await publicFund.close();
  await page.locator('.attestation-list > button').filter({ hasText: 'ATT-DEMO-0118' }).click();
  await page.getByRole('button', { name: 'Registra revisione demo' }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.getByRole('button', { name: 'Registra esito demo' }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.locator('.attestation-document__header .status-badge')).toContainText('Verificato');
  await expect(page.locator('.review-timeline')).toContainText('Verifica demo completata');
  await noOverflow(page, 'C02 desktop');
  await dismissToasts();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: 'qa/area1-c02-desktop.png' });

  await page.locator('.workspace-nav a[href="/app/report"]').click();
  await expect(page.locator('.template-launcher > button')).toHaveCount(4);
  await page.locator('.template-launcher > button').filter({ hasText: 'Sintesi Stakeholder' }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.getByRole('dialog').locator('textarea').fill('Sintesi QA del valore sociale e ambientale della commessa, con dati sintetici e fonti tracciate.');
  await page.getByRole('button', { name: 'Crea bozza e collega i dati' }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.locator('.report-canvas__header .status-badge')).toContainText('Bozza');
  await expect(page.locator('.page-budget')).toContainText('2 max');
  const editor = page.locator('.report-editor textarea');
  await editor.fill('Versione due della sintesi QA. Perimetro, dati e ordini restano invariati; il testo è una simulazione non valida per reporting.');
  await page.getByRole('button', { name: 'Salva versione' }).click();
  await expect(page.getByRole('button', { name: /Confronta 1 versioni/ })).toBeVisible();
  await expect(page.locator('.composer-outline__version strong')).toHaveText('v2');
  await page.getByRole('button', { name: /Confronta 1 versioni/ }).click();
  await expect(page.locator('.report-diff')).toContainText('Versione due');
  await page.getByRole('button', { name: 'Invia a revisione' }).click();
  await page.getByRole('button', { name: 'Conferma invio' }).click();
  await expect(page.locator('.report-canvas__header .status-badge')).toContainText('In revisione');
  await page.getByRole('button', { name: 'Registra revisione demo' }).click();
  await page.getByRole('button', { name: 'Registra esito demo' }).click();
  await expect(page.locator('.report-canvas__header .status-badge')).toContainText('Verificato');
  await expect(editor).toBeDisabled();
  const reportPdf = await clickExport('pdf');
  assert.match(reportPdf.suggestedFilename(), /report-.*\.pdf$/);
  await noOverflow(page, 'C03 desktop');
  await dismissToasts();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: 'qa/area1-c03-desktop.png' });

  await page.locator('.workspace-nav a[href="/app/evidence-packs"]').click();
  await expect(page.locator('.completeness-block strong')).toHaveText('75%');
  await expect(page.locator('.checklist-item')).toHaveCount(4);
  const missingPolicy = page.locator('.checklist-item').filter({ hasText: 'Protocollo di approvvigionamento sostenibile' });
  await missingPolicy.locator('select').selectOption('EV-PROC-001');
  await missingPolicy.getByRole('button', { name: 'Collega', exact: true }).click();
  await expect(page.locator('.completeness-block strong')).toHaveText('100%');
  await page.getByRole('button', { name: 'Invia a revisione' }).click();
  await page.getByRole('button', { name: 'Conferma invio' }).click();
  await expect(page.locator('.pack-status-header > .status-badge')).toContainText('In revisione');
  await page.getByRole('button', { name: 'Registra revisione demo' }).click();
  await page.getByRole('button', { name: 'Registra esito demo' }).click();
  await expect(page.locator('.pack-status-header > .status-badge')).toContainText('Verificato');
  const zip = await clickExport('zip');
  assert.match(zip.suggestedFilename(), /evidence-pack-.*\.zip$/);
  const zipBuffer = await fs.readFile(await zip.path());
  assert.equal(zipBuffer.subarray(0, 2).toString(), 'PK');
  await page.locator('.module-heading__actions').getByRole('button', { name: 'Condividi' }).click();
  await page.getByRole('button', { name: 'Crea un nuovo link di 24 ore' }).click();
  await expect(page.locator('.share-item')).toHaveCount(1);
  const publicPackUrl = await page.locator('.share-item > code').innerText();
  const publicPack = await context.newPage();
  await publicPack.goto(publicPackUrl, { waitUntil: 'networkidle' });
  await expect(publicPack.locator('.public-pack-card')).toBeVisible();
  await expect(publicPack.locator('.public-pack-summary')).toContainText('4/4');
  const publicPackText = await publicPack.locator('main').innerText();
  assert.ok(!publicPackText.includes('15.000') && !publicPackText.includes('Bonifico'), 'Public pack leaks private evidence data');
  await noOverflow(publicPack, 'public pack desktop');
  await publicPack.close();
  await page.reload({ waitUntil: 'networkidle' });
  await page.locator('.module-heading__actions').getByRole('button', { name: 'Condividi' }).click();
  await expect(page.locator('.share-item__top')).toContainText('1 visualizzazioni');
  await page.getByRole('button', { name: 'Revoca', exact: true }).click();
  await page.getByRole('button', { name: 'Revoca immediatamente' }).click();
  await expect(page.locator('.share-item .status-badge')).toContainText('Revocato');
  const revoked = await context.newPage();
  await revoked.goto(publicPackUrl, { waitUntil: 'networkidle' });
  await expect(revoked.getByRole('heading', { name: 'Link scaduto o revocato.' })).toBeVisible();
  await revoked.close();
  await page.getByRole('dialog').first().getByRole('button', { name: 'Chiudi finestra' }).click();
  await page.getByRole('tab', { name: /Assurance Pack/ }).click();
  await expect(page.locator('.checklist-item')).toHaveCount(5);
  await expect(page.locator('.completeness-block strong')).toHaveText('100%');
  await expect(page.locator('.isae-note')).toContainText('ISAE 3000');
  await noOverflow(page, 'C04 desktop');
  await dismissToasts();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: 'qa/area1-c04-desktop.png' });

  const mobileContext = await browser.newContext({ viewport: { width: 390, height: 844 } });
  const mobile = await mobileContext.newPage();
  mobile.on('pageerror', (error) => errors.push(`mobile pageerror: ${error.message}`));
  mobile.on('console', (message) => { if (message.type() === 'error') errors.push(`mobile console: ${message.text()}`); });
  await mobile.goto(`${base}/app/esg/scope-3`, { waitUntil: 'networkidle' });
  await expect(mobile.locator('.dataset-detail')).toBeVisible();
  await noOverflow(mobile, 'C01 mobile');
  await mobile.screenshot({ path: 'qa/area1-c01-mobile.png', fullPage: true });
  await mobile.getByRole('button', { name: 'Apri navigazione workspace' }).click();
  await expect(mobile.locator('.workspace-sidebar.is-open')).toBeVisible();
  await mobile.locator('.workspace-nav a[href="/app/report"]').click();
  await expect(mobile.locator('.report-canvas')).toBeVisible();
  await noOverflow(mobile, 'C03 mobile');
  await mobile.screenshot({ path: 'qa/area1-c03-mobile.png' });
  await mobile.goto(`${base}/app/evidence-packs?type=ASSURANCE`, { waitUntil: 'networkidle' });
  await expect(mobile.locator('.pack-workspace')).toBeVisible();
  await noOverflow(mobile, 'C04 mobile');
  await mobile.screenshot({ path: 'qa/area1-c04-mobile.png' });
  await mobileContext.close();

  assert.deepEqual(errors, [], `Browser errors: ${errors.join('\n')}`);
  console.log('AREA 1 E2E PASS — 7 card routes, C01 compare/export/history, C02 reconciliation/review/public minimization, C03 create/version/diff/review/export, C04 evidence/review/ZIP/share/view/revoke, desktop/mobile overflow, no browser errors.');
} finally {
  await browser.close();
  await fs.writeFile('data/area1.json', seedBackup, 'utf8');
}
